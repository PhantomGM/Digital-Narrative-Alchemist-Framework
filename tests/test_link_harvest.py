"""
Tests for the registry/vault reconciliation.

The harvest writes into the edge store that feeds every generation prompt's
LINEAGE layer, so a wrong edge is not cosmetic — it becomes context the model is
told is true. The properties that matter:

  * full-name matching only, never a fragment. 'Aetherium' inside 'Aetherium
    Shards' must not link every artifact to every other one;
  * hubs are not relationships. An Index that lists all 70 pages would otherwise
    connect everything to everything;
  * relationships the registry already holds are never duplicated;
  * canon page text is read and never written.
"""

import os
import sys

import pytest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..', 'src'))

from layer5_dna_substrate.link_harvest import (  # noqa: E402
    apply_edges, candidate_entities, entity_index, harvest_edges, load_pages,
    register_entities, render_worklist, unlinked_character_pairs,
)
from layer5_dna_substrate.registry import DNARegistry  # noqa: E402


def page(vault, folder, stem, body, status="draft"):
    path = os.path.join(vault, folder) if folder else vault
    os.makedirs(path, exist_ok=True)
    with open(os.path.join(path, stem + ".md"), "w", encoding="utf-8") as fh:
        fh.write(f"---\nstatus: {status}\n---\n\n{body}")


@pytest.fixture
def world(tmp_path):
    vault = str(tmp_path)
    reg = DNARegistry()
    ids = {
        "Emberhold": reg.register_element("settlement", "S{}", "b",
                                          name="Emberhold", tags=["canonized"]),
        "Archivist Kaelen": reg.register_element("npc", "N{}", "b",
                                                 name="Archivist Kaelen"),
        "Chief Scrivener Lyra": reg.register_element("npc", "N{}", "b",
                                                     name="Chief Scrivener Lyra"),
        "Aetherium Shards": reg.register_element("item", "I{}", "b",
                                                 name="Aetherium Shards"),
        "Aetherium": reg.register_element("lore", "L{}", "b", name="Aetherium"),
    }
    page(vault, "Atlas", "Emberhold",
         "The city trades in [[Aetherium Shards]]. Archivist Kaelen walks here.",
         status="canon")
    page(vault, "Characters", "Archivist Kaelen",
         "He keeps the stacks. He fears Chief Scrivener Lyra.")
    page(vault, "Characters", "Chief Scrivener Lyra", "She rules the Guild.")
    page(vault, "Artifacts", "Aetherium Shards", "Shards of raw power.")
    page(vault, "Lore", "Aetherium", "A substance nobody understands.")
    return vault, reg, ids


def test_hub_and_template_pages_are_ignored(world):
    vault, reg, _ = world
    page(vault, "", "Index", "[[Emberhold]] [[Archivist Kaelen]]")
    page(vault, "Templates", "Character", "[[Emberhold]]")
    page(vault, "Atlas", "Atlas", "[[Emberhold]]")
    pages = load_pages(vault)

    assert "Index" not in pages
    assert "Character" not in pages
    assert "Atlas" not in pages, "a folder note is navigation, not content"
    assert "Emberhold" in pages


def test_the_deriver_does_not_read_its_own_output(world):
    """
    The worklist names every character, so if it were treated as content each
    pair would cite it as a page they share -- evidence generated by the run
    that reports it.
    """
    vault, reg, _ = world
    page(vault, "Drafts", "Link Gaps",
         "| [[Archivist Kaelen]] | [[Chief Scrivener Lyra]] |\n"
         "Archivist Kaelen and Chief Scrivener Lyra")
    with open(os.path.join(vault, "Drafts", "Link Gaps.md"),
              "w", encoding="utf-8") as fh:
        fh.write("---\ntype: meta\nstatus: draft\n---\n\n"
                 "Archivist Kaelen and Chief Scrivener Lyra")
    pages = load_pages(vault)

    assert "Link Gaps" not in pages
    assert all("Link Gaps" not in r["shared_pages"]
               for r in unlinked_character_pairs(reg, pages))


def test_wikilink_the_registry_lacks_is_harvested(world):
    vault, reg, ids = world
    rows = harvest_edges(reg, load_pages(vault))
    hit = [r for r in rows
           if r["source"] == "Emberhold" and r["target"] == "Aetherium Shards"]

    assert len(hit) == 1
    assert hit[0]["kind"] == "wikilink"
    assert hit[0]["label"] == "mentions_Aetherium Shards"


def test_bare_prose_mention_is_harvested_as_prose(world):
    vault, reg, _ = world
    rows = harvest_edges(reg, load_pages(vault))
    hit = [r for r in rows
           if r["source"] == "Archivist Kaelen"
           and r["target"] == "Chief Scrivener Lyra"]

