def test_harvest_never_writes_to_the_vault(world):
    vault, reg, _ = world
    before = {p: open(os.path.join(r, f), encoding="utf-8").read()
              for r, _, fs in os.walk(vault) for f in fs
              for p in [os.path.join(r, f)]}
    pages = load_pages(vault)
    harvest_edges(reg, pages)
    candidate_entities(reg, pages)
    unlinked_character_pairs(reg, pages)
    after = {p: open(p, encoding="utf-8").read() for p in before}

    assert before == after, "canon is read-only to this deriver"


def test_worklist_renders_without_a_dataview_dependency(world):
    vault, reg, _ = world
    pages = load_pages(vault)
    text = render_worklist(unlinked_character_pairs(reg, pages),
                           candidate_entities(reg, pages),
                           harvest_edges(reg, pages))

    assert text.startswith("---\n")
    assert "# Link Gaps" in text
    assert "dataview" not in text
